# ---------------------------------------------------------------- numbers (verified)
X1, Y1 = 2400, 9100
HS = w.handshake(X1, Y1)
assert HS == [("C", "SYN", 2400, None), ("S", "SYN+ACK", 9100, 2401), ("C", "ACK", 2401, 9101)]
FIRST_DATA = HS[2][2]
assert FIRST_DATA == X1 + 1 == 2401


def lab(m):
    _, f, s, a = m
    return f"{f} seq={s}" + (f" ack={a}" if a is not None else "")


LAD, _ = w.ladder("hs", ("לקוח", "שרת"), [
    dict(dir="R" if m[0] == "C" else "L", label=lab(m), cls="syn" if "SYN" in m[1] else "ack") for m in HS],
    step=120, slope=70)

# exam-style: a captured SYN+ACK (seq=4200, ack=8801); what was in the SYN, and what will the ACK carry?
CAP_SEQ, CAP_ACK = 4200, 8801
x = CAP_ACK - 1                       # the server acknowledges x+1
REB = w.handshake(x, CAP_SEQ)
assert REB[1] == ("S", "SYN+ACK", CAP_SEQ, CAP_ACK)          # the reconstruction reproduces the capture
SYN_SEQ, M3 = REB[0][2], REB[2]
assert SYN_SEQ == 8800 and M3[2:] == (8801, 4201)
OPTS_V = {"a": (8800, 8801, 4201), "b": (8801, 8801, 4200), "c": (8800, 8800, 4201), "d": (4200, 4201, 8801)}
CORRECT = [k for k, v in OPTS_V.items() if v == (SYN_SEQ, M3[2], M3[3])]
assert CORRECT == ["a"]
OPTS = [(k, w.ltr(f"SYN {a} · ACK ({b}, {c})")) for k, (a, b, c) in OPTS_V.items()]
CAP, _ = w.ladder("cp", ("לקוח", "שרת"), [
    dict(dir="R", label="SYN seq=?", cls="syn"),
    dict(dir="L", label=f"SYN+ACK seq={CAP_SEQ} ack={CAP_ACK}", cls="syn"),
    dict(dir="R", label="ACK seq=? ack=?", cls="ack")], step=110, slope=64)

