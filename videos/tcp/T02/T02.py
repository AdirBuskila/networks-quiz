# exam-style: after the handshake A sends seq=6001 with 400 bytes, then 250, then 350; all arrive in order
Q0, LENS = 6001, [400, 250, 350]
starts = [Q0, Q0 + LENS[0], Q0 + LENS[0] + LENS[1]]
segs = [(s, s + n - 1) for s, n in zip(starts, LENS)]
QA = w.acks(segs, Q0)
assert starts[2] == 6651 and QA == [6401, 6651, 7001]
OPTS_V = {"a": (6651, 7001), "b": (6650, 7000), "c": (6003, 6004), "d": (6651, 6652)}
assert OPTS_V["b"] == (starts[2] - 1, QA[2] - 1)            # counted the last byte instead of the next one
assert OPTS_V["c"] == (Q0 + 2, Q0 + 3)                      # counted segments, not bytes
assert OPTS_V["d"] == (starts[2], starts[2] + 1)            # +1 as if the segment were a SYN
assert [k for k, v in OPTS_V.items() if v == (starts[2], QA[2])] == ["a"]
OPTS = [(k, w.ltr(f"seq={a}, ack={b}")) for k, (a, b) in OPTS_V.items()]

