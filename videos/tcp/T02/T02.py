# ---------------------------------------------------------------- numbers (verified)
S1, L1 = 3000, 250
assert w.seg_end(S1, L1) == (3249, 3250)
assert w.acks([(3000, 3249)], 3000) == [3250]
A, B = 51, 450
assert B - A + 1 == 400 and w.acks([(A, B)], A) == [451]
# cumulative: three 200-byte segments from 801; the ACK 1201 is lost on the way back
SEGS = [(801, 1000), (1001, 1200), (1201, 1400)]
ACKS = w.acks(SEGS, 801)
assert ACKS == [1001, 1201, 1401]
# after the handshake: x = 7199 -> data from 7200, 120 bytes -> ack 7320
XH = 7199
assert w.handshake(XH, 0)[2][2] == 7200 and w.seg_end(7200, 120) == (7319, 7320)

