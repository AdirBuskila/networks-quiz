# ---------------------------------------------------------------- numbers (verified)
B1 = 2500
assert B1 * w.BIT_PER_BYTE == 20000                        # 2,500 Bytes = 20,000 bit
R1 = 40 * w.M
assert R1 == 4 * 10**7                                      # 40 Mbps = 4·10^7 bps
assert F(20, 1000) == F(2, 100)                             # 20 ms = 0.02 s
assert F(250, 10**6) == F(25, 10**5)                        # 250 µs = 2.5·10^-4 s
assert w.fmt(F(250, 10**6)) == "0.00025"
A_H = 540000
assert F(A_H, 3600) == 150 and F(A_H, 60) == 9000 and F(9000, 60) == 150

# exam-style: 900,000 packets per hour, 1,250 Bytes each -> bits per second
QA, QB = 900000, 1250
a = F(QA, 3600)
Lbits = QB * 8
rate = a * Lbits
assert a == 250 and Lbits == 10000 and rate == F(25, 10) * w.M          # 2.5 Mbps
no8 = a * QB
no3600 = QA * Lbits
only60 = F(QA, 60) * Lbits
assert no8 == F(3125, 10**4) * w.M                                         # 0.3125 Mbps (forgot ×8)
assert no3600 == 9000 * w.M                                                # 9,000 Mbps (forgot ÷3600)
assert only60 == 150 * w.M                                                 # 150 Mbps (÷60 only)
OPTS = [(k, w.ltr(v)) for k, v in [("a", "0.3125 Mbps"), ("b", "2.5 Mbps"), ("c", "150 Mbps"), ("d", "9,000 Mbps")]]
CORRECT = "b"
VALUES = {"a": no8, "b": rate, "c": only60, "d": no3600}
assert [k for k, v in VALUES.items() if v == rate] == [CORRECT]
assert {k: w.fmt(v / w.M) for k, v in VALUES.items()} == {"a": "0.3125", "b": "2.5", "c": "150", "d": "9,000"}

