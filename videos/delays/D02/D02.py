"""D02 · השהיית שידור L/R — video script (build: tools/video/vid.py D02).

Source: courses/delays/C02.js (lesson + goal: the time to push a packet or a file onto the link, L/R).
Exam part: an original question "בסגנון מבחן" (bank={}): the delays topic has no free bank question about L/R alone
(24A-A-Q2 and 25A-C-Q3 anchor D06 and D04).
Avoided on purpose: the C02 quiz numbers (8,000 bit on 10 Mbps, 1500 Bytes on 100 Mbps and on 1 Gbps, 1 MB on
10 Mbps, 20 vs 40 Mbps) and the lesson's examples (1500 Bytes / 100 Mbps, 1 MB / 10 Mbps).
The animation is w_delays.link_frames (bit k leaves at k/R); every delay is an exact fraction asserted below.
"""
from fractions import Fraction as F
from vid import P, Scene, Video, show, hide
