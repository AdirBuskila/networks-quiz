# ---------------------------------------------------------------- numbers (verified)
L1, R1 = 16000, 40 * w.M
T1 = w.trans(L1, R1)
assert T1 == F(4, 10**4) and w.ms(T1) == F(4, 10)                     # 0.4 ms
D1, S1 = 80 * w.K, 2 * 10**8               # an 80 km link: d/s = L/R, so the front reaches B as the last bit leaves A
TIMES = [F(1, 10**4), F(2, 10**4), F(4, 10**4)]
LINK, STATS = w.link_frames("lk", L1, R1, D1, S1, TIMES)
assert [s[0] for s in STATS] == [4000, 8000, 16000]                    # bits sent after 0.1, 0.2, 0.4 ms
assert [s[2] for s in STATS] == [0, 0, 0] and w.prop(D1, S1) == T1    # none has arrived yet
assert w.trans(L1, 2 * R1) == T1 / 2 and w.ms(w.trans(L1, 2 * R1)) == F(2, 10)   # 80 Mbps: 0.2 ms
assert w.trans(2 * L1, R1) == 2 * T1                                   # double packet: double time
# the same packet given as 2,000 Bytes, forgetting ×8
assert 2000 * 8 == L1 and w.ms(w.trans(2000, R1)) == F(5, 100) and T1 / w.trans(2000, R1) == 8
# a file: 5 MB on 25 Mbps
LF, RF = 5 * w.M * 8, 25 * w.M
assert LF == 4 * 10**7 and w.trans(LF, RF) == F(16, 10)                # 1.6 s

# exam-style: 3 MB (3·10^6 Bytes) on 12 Mbps
QL, QR = 3 * w.M * 8, 12 * w.M
ANS = w.trans(QL, QR)
assert QL == 24 * 10**6 and ANS == 2
V = {"a": w.trans(3 * w.M, QR), "b": F(QR, QL), "c": ANS, "d": w.trans(QL, 12 * w.K)}
assert V == {"a": F(1, 4), "b": F(1, 2), "c": 2, "d": 2000}
assert [k for k, v in V.items() if v == ANS] == ["c"]
OPTS = [("a", "0.25 שנייה"), ("b", "0.5 שנייה"), ("c", "2 שניות"), ("d", "2,000 שניות")]

