# ---------------------------------------------------------------- max arrival rate: 50 Mbps, 1,250 Bytes, ρ = 0.6
R1, L1, RHO1 = 50 * w.M, 1250 * 8, F(6, 10)
A1 = RHO1 * R1 / L1
assert L1 == 10000 and A1 == 3000 and A1 * 60 == 180000 and w.rho(A1, L1, R1) == RHO1
assert R1 / L1 == 5000                                                    # ρ = 1 would allow 5,000 per second

# ---------------------------------------------------------------- throughput: server 30, shared 60 over 3, client 25
SV, SH, K3, CL = 30, 60, 3, 25
share = F(SH, K3)
PATH, BN = w.rate_path("pt", [("s", "server", SV), ("m", "shared ÷ 3", share), ("c", "client", CL)])
thr = min(F(SV), share, F(CL))
assert share == 20 and thr == 20 and BN == "m"
assert thr / SV == F(2, 3) and round(float(thr / SV), 2) == 0.67 and thr / CL == F(4, 5)

# ---------------------------------------------------------------- exam 24A-A-Q2
Q = BANK["24A-A-Q2"]
assert Q["correctId"] == "a"
QR, QL, QRHO = 10 * w.G, 5000, F(8, 10)
QA = QRHO * QR / QL
assert QA == 1600000
VALS = {o["id"]: int(o["value"].split()[0].replace(",", "")) for o in Q["options"]}
assert VALS == {"a": 1600000, "b": 8000000, "c": 16000000, "d": 32000000}
BACK = {k: w.rho(v, QL, QR) for k, v in VALS.items()}                     # plug each option back into aL/R
assert BACK == {"a": F(8, 10), "b": 4, "c": 8, "d": 16}
assert QR / QL == 2000000 and [k for k, v in VALS.items() if v > QR / QL] == ["b", "c", "d"]   # above the ρ = 1 ceiling
OPTS = [(o["id"], o["value"]) for o in Q["options"]]

