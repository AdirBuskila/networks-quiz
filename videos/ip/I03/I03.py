# ---------------------------------------------------------------- numbers (verified)
E1, P1 = "84.12.170.33", 27
N1, B1 = w.block(f"{E1}/{P1}")
assert (N1, B1) == ("84.12.170.32", "84.12.170.63") and w.boundary(P1) == (3, 32)
assert w.bits32(N1)[P1:] == "0" * 5 and w.bits32(B1)[P1:] == "1" * 5
assert w.bits32(N1)[:P1] == w.bits32(E1)[:P1] == w.bits32(B1)[:P1]

E2, P2 = "61.130.99.5", 12
N2, B2 = w.block(f"{E2}/{P2}")
assert (N2, B2) == ("61.128.0.0", "61.143.255.255") and w.boundary(P2) == (1, 16)
assert 130 // 16 * 16 == 128 and 128 + 16 - 1 == 143
IN, OUT = "61.143.200.7", "61.144.0.1"
assert ia.ip_address(IN) in w.net(f"{E2}/{P2}") and ia.ip_address(OUT) not in w.net(f"{E2}/{P2}")

# exam-style: 150.40.77.200/19, first and last address
EX, PX = "150.40.77.200", 19
first, last = w.block(f"{EX}/{PX}")
assert (first, last) == ("150.40.64.0", "150.40.95.255") and w.boundary(PX) == (2, 32)
as_given = str(ia.ip_address(EX) + w.addresses(PX) - 1)
assert as_given == "150.40.109.199"
OPTV = {"a": (first, last),
        "b": w.block(f"{EX}/24"),                       # the boundary byte left as is
        "c": w.block(f"{EX}/18"),                       # block size 64 instead of 32
        "d": (EX, as_given)}                            # the given address taken as the first one
assert OPTV["b"] == ("150.40.77.0", "150.40.77.255") and OPTV["c"] == ("150.40.64.0", "150.40.127.255")
assert len(set(OPTV.values())) == 4
ORDER = ["c", "a", "d", "b"]
OPTS = [(k, w.mono(f"{OPTV[k][0]} – {OPTV[k][1]}")) for k in ORDER]


