# ---------------------------------------------------------------- numbers (verified)
S1, MTU1 = 1500, 576
D1 = S1 - 20
FR1 = w.frag(D1, MTU1)
assert D1 == 1480 and (MTU1 - 20) == 556 and 556 % 8 == 4 and 556 // 8 * 8 == 552
assert FR1 == [(552, 572, 0, 1), (552, 572, 69, 1), (376, 396, 138, 0)]
assert 556 / 8 == 69.5

# exam 23A-A-Q1: which Offset values can the 5th of exactly 5 fragments carry?
Q = BANK["23A-A-Q1"]
assert Q["correctId"] == "b"
VAL = {o["id"]: int(o["value"].split("=")[1]) for o in Q["options"]}
assert VAL == {"a": 1600, "b": 200, "c": 400, "d": 480, "e": 405}
possible = set()
for D in (1980, 2000):                       # "2000 Bytes" with or without the header: both give the same answer
    for k in range(8, 4000, 8):
        if 4 * k < D <= 5 * k:
            assert len(w.frag(D, k + 20)) == 5
            possible.add(4 * k // 8)
assert min(possible) == 200 and max(possible) == 248 and all(v % 4 == 0 for v in possible)
assert [k for k, v in VAL.items() if v in possible] == ["b"]
assert w.frag(1980, 420)[4] == (380, 400, 200, 0)            # MTU 420 (the sister question): k = 400
assert len(w.frag(1980, 800 + 20)) == 3 and len(w.frag(1980, 960 + 20)) == 3     # 400 and 480 need k = 800 / 960
assert 810 % 8 != 0                                            # 405 would need k = 810
OPTS = [(o["id"], w.ltr(o["value"].replace(" ", ""))) for o in Q["options"]]

FB1, _ = w.fbar("fa", D1, MTU1)
FBX, _ = w.fbar("fx", 1980, 420)


def fr_ids(pfx, j, *kinds):
    return [f"{pfx}-{k}-{j}" for k in kinds]


