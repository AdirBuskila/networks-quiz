# ---------------------------------------------------------------- numbers (verified)
BASE = "172.30.64.0/18"
SUBS = [str(n) for n in ia.ip_network(BASE).subnets(prefixlen_diff=2)]
assert SUBS == ["172.30.64.0/20", "172.30.80.0/20", "172.30.96.0/20", "172.30.112.0/20"]
assert ia.ip_network(SUBS[0]).num_addresses == 4096 == 2 ** (32 - 20)
assert w.boundary(20) == (2, 16)

H = {h: 2 ** h - 2 for h in (8, 9, 10)}
assert H == {8: 254, 9: 510, 10: 1022}
assert w.min_host_bits(500) == 9 and 32 - 9 == 23
assert w.min_host_bits(511) == 10 and 32 - 10 == 22
assert w.min_host_bits(510) == 9
assert len(list(ia.ip_network("10.0.0.0/22").subnets(new_prefix=25))) == 8 == 2 ** (25 - 22)

# exam-style: 10.40.4.0/22, at least 130 hosts per subnet, as many subnets as possible
XB, NEED = "10.40.4.0/22", 130
hx = w.min_host_bits(NEED)
px = 32 - hx
XS = [str(n) for n in ia.ip_network(XB).subnets(new_prefix=px)]
assert (hx, px) == (8, 24) and XS == ["10.40.4.0/24", "10.40.5.0/24", "10.40.6.0/24", "10.40.7.0/24"]
assert w.hosts(25) == 126 < NEED <= w.hosts(24) == 254
OPTV = {"a": len(XS),
        "b": len(list(ia.ip_network(XB).subnets(new_prefix=25))),     # /25: only 126 hosts
        "c": ia.ip_network(XB).num_addresses // NEED,                 # plain division, ignores powers of two
        "d": len(list(ia.ip_network(XB).subnets(new_prefix=23)))}     # /23: enough, but not as many
assert OPTV == {"a": 4, "b": 8, "c": 7, "d": 2} and 1024 / 130 > 7
ORDER = ["b", "c", "a", "d"]
OPTS = [(k, f"{OPTV[k]} תת-רשתות") for k in ORDER]

SB = w.strip("sb", "172.30.64.0", 18, borrow=20)


def blocks_show(pfx, starts):
    return [x for s in starts for x in (f"{pfx}-b-{s}", f"{pfx}-r-{s}")]


