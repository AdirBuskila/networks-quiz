"""I04 · חלוקה לתת-רשתות — video script (build: tools/video/vid.py I04).

Source: courses/ip/C04.js (lesson + goal: split a block into equal subnets; shortest prefix for n hosts).
Exam part: an original question "בסגנון מבחן" (bank={}): the bank has no subnetting question.
Avoided on purpose: every case of the C04 quiz and lesson (192.168.5.0/24 into 4 and its third subnet, /24 into 8,
30 / 31 / 50 / 100 hosts, /20 in /16). Worked examples: 172.30.64.0/18 into 4, 500 and 511 hosts, /25 in /22;
exam: 10.40.4.0/22 with at least 130 hosts per subnet.
Every subnet list and prefix is computed with ipaddress (subnets(), num_addresses) and asserted.
"""
import ipaddress as ia
