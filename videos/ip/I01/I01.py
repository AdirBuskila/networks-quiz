# ---------------------------------------------------------------- numbers (verified)
A1 = "139.45.7.250"
assert w.bits32(A1) == "10001011" "00101101" "00000111" "11111010"

B1 = 0b10110110
assert B1 == 182 == 128 + 32 + 16 + 4 + 2
assert [128 >> i for i, c in enumerate(format(B1, "08b")) if c == "1"] == [128, 32, 16, 4, 2]

D1 = 172
STEPS = w.to_bin_steps(D1)
assert format(D1, "08b") == "10101100" and D1 == 128 + 32 + 8 + 4
assert [r for _, _, r in STEPS] == [44, 44, 12, 12, 4, 0, 0, 0]


def valid(s):
    try:
        ia.IPv4Address(s)
        return True
    except ValueError:
        return False


CHK = [("8.8.4.4", True), ("10.256.1.1", False), ("192.168.1", False), ("1.2.3.4.5", False)]
assert all(valid(a) == v for a, v in CHK)
assert 2 ** 32 == 4294967296

Q = BANK["22S-A-Q2"]
