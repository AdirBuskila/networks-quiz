def parse(opt):
    rows = []
    for line in re.findall(r"`([^`]+)`", opt["value"]):
        f = dict(re.findall(r"(SRC IP|DST IP|SRC PORT|DST PORT|SIZE|OFFSET|FRAG) ([\d.]+)", line))
        rows.append(f)
    return rows


PK = {o["id"]: parse(o) for o in Q1["options"]}
assert all(r["DST IP"] == "20.0.3.1" and r["DST PORT"] == "80" for v in PK.values() for r in v)
want = [{"SRC IP": "10.0.0.1", "SRC PORT": "123", "SIZE": str(s), "OFFSET": str(o), "FRAG": str(m)} for _, s, o, m in FR]
fit = [k for k, v in PK.items() if [{x: r[x] for x in want[0]} for r in v] == want]
assert fit == ["a"]
assert [r["SRC IP"] for r in PK["b"]] == ["20.0.0.1"] * 2 and [r["SRC PORT"] for r in PK["b"]] == ["130"] * 2
assert len(PK["c"]) == 1 and PK["c"][0]["SIZE"] == "2000" and 2000 + 20 > 1500
assert [r["SRC IP"] for r in PK["d"]] == ["10.0.0.1", "20.0.0.1"]


